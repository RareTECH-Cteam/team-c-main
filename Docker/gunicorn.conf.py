# ================================================================
# gunicorn設定ファイル
# ================================================================
import multiprocessing
import os

# ================================================================
# バインドアドレス
# ================================================================
# Docker 内で Gunicorn が listen するポート
bind = "0.0.0.0:8000"

# ================================================================
# ワーカー設定
# ================================================================
# 環境変数 GUNICORN_WORKERS の指定があれば優先
workers = int(os.environ.get("GUNICORN_WORKERS", multiprocessing.cpu_count() * 2 + 1))

# ワーカークラス
# gthread = ワーカーが複数スレッドを持つ 
# 環境変数 GUNICORN_THREADS の指定があれば優先
worker_class = "uvicorn.workers.UvicornWorker"

# ================================================================
# タイムアウト
# ================================================================
# リクエスト処理タイムアウト (秒)
timeout = 60

# ワーカー正常終了までの猶予時間(処理中のリクエストがあれば完了するのを待つ)
graceful_timeout = 30

# クライアント接続維持時間(ALB → gunicorn 間の接続維持)
keepalive = 5

# ================================================================
# ログ設定
# ================================================================
# アクセスログ・エラーログをdockerの標準出力へ
accesslog = "-"
errorlog = "-"

# ログレベル
# 環境変数 GUNICORN_LOG_LEVEL の指定があれば優先
loglevel = os.environ.get("GUNICORN_LOG_LEVEL", "info")

# アクセスログフォーマット
access_log_format = (
    '%(h)s "%(r)s" %(s)s %(b)s "%(a)s" %(L)s'
)

# ================================================================
# その他
# ================================================================
# プロセスタイトル
proc_name = "keigo-api"

# 1 ワーカーあたりの最大リクエスト数(これを超えたらワーカー再起動=メモリ解放)
max_requests = 1000

# 各ワーカーの再起動タイミングをずらす
max_requests_jitter = 100

# アプリのプリロード
# False: 各ワーカーが個別にロード
# True: linuxの仕組みで各workerが同じメモリを共有できメモリ効率良いがデプロイ時に全ワーカー再起動が必要
preload_app = False
